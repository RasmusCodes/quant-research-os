"""The demo research project: a scripted, realistic research workflow on the synthetic market.

``build_demo(path)`` creates a registry and replays about two months of research (simulated clock,
January-March 2025): data deliveries and a vendor correction, seven hypotheses, parameter sweeps,
model versions, a look-ahead mistake, a survivorship-biased universe, a hypothesis rewritten after the
results, holdout over-use, an unseeded random generator, and final confirmatory tests on a sealed
holdout. Every number comes from running the strategies in qros.examples.strategies on data from
qros.examples.synthetic_market; nothing is typed in. Timestamps are simulated and labelled as such.

Run it with ``qros demo --out demo-registry``.
"""

from __future__ import annotations

import time
from pathlib import Path
from typing import Any, Callable

import pandas as pd

from qros.data.corporate_actions import adjust_prices
from qros.data.pit import PointInTime
from qros.evaluate import revalidate_all
from qros.examples.strategies import ma_grid, month_ends
from qros.examples.synthetic_market import MarketConfig, generate
from qros.registry import db
from qros.registry.core import Registry
from qros.registry.models import Periods
from qros.runner import reproduce, run_experiment
from qros.util.hashing import canonical_json
from qros.util.timeutil import SimulatedClock

DEMO_SEED = 20261121
TRAIN = ("2005-01-01", "2014-12-31")
TEST = ("2015-01-01", "2019-12-31")
SEEN = ("2005-01-01", "2019-12-31")
S = "qros.examples.strategies"


def build_demo(path: str | Path, *, seed: int = DEMO_SEED, quick: bool = False,
               log: Callable[[str], None] = print) -> Registry:
    started = time.time()
    clock = SimulatedClock("2025-01-06T08:30:00Z", tick_seconds=3)
    reg = Registry.init(path, clock=clock, researcher="demo researcher")
    cfg = MarketConfig(seed=seed, n_assets=40 if quick else 200)
    log(f"generating the synthetic market (seed {seed}, {cfg.n_assets} firms)")
    m = generate(cfg)
    truth: dict[str, dict[str, Any]] = {}
    periods = Periods.of(TRAIN, TEST)
    seen = Periods.of(SEEN, None)

    def run(entry: str, name: str, *, label: str, real: bool | None, **kw: Any) -> str:
        exp = run_experiment(reg, f"{S}:{entry}" if ":" not in entry else entry, name=name, **kw)
        truth[exp.id] = {"label": label, "planted_effect": real}
        clock.advance(minutes=4)
        log(f"  {exp.id} {name}: {exp.verdict}")
        return exp.id

    # ------------------------------------------------------------------ data deliveries (6 Jan 2025)
    src = reg.add_source("SynthVendor (synthetic)", vendor="qros.examples.synthetic_market",
                         license="Synthetic data generated by qros; no real securities",
                         description=f"Simulated market, seed {seed}. Ground truth is known by construction.")
    reg.add_dataset("equity-prices-raw", source=src, kind="raw", frequency="B", survivorship_free=True,
                    adjusted=False, description="Unadjusted daily closes of every firm ever listed (dates x tickers).")
    reg.add_dataset("corporate-actions", source=src, kind="events", entity_col="entity", time_col="date",
                    description="Splits (new shares per old) and cash dividends per post-split share, by ex-date.")
    reg.add_dataset("equity-prices-adjusted", source=src, kind="table", frequency="B", survivorship_free=True,
                    adjusted=True, description="Closes adjusted for splits and dividends (total-return prices).")
    reg.add_dataset("fundamentals-quarterly", source=src, kind="table", entity_col="ticker", time_col="period_end",
                    available_col="available_at",
                    description="Quarterly profitability with the date each report was published (point in time).")
    reg.add_dataset("universe-pit", source=src, kind="universe", survivorship_free=True,
                    description="Every firm ever listed, with listing and delisting dates.")
    reg.add_dataset("universe-survivors", source=src, kind="universe", survivorship_free=False,
                    description="Only firms still listed at the end of 2024: survivorship-biased by design.")
    reg.add_dataset("futures-returns", source=src, kind="raw", frequency="B",
                    description="Daily returns of one synthetic futures contract.")
    reg.add_dataset("feature-momentum-12-1", source=src, kind="feature",
                    description="Month-end 12-1 month past returns (feature store snapshot).")
    reg.add_dataset("feature-profitability-pit", source=src, kind="feature",
                    description="Month-end profitability as published (point-in-time feature store snapshot).")

    clock.set("2025-01-06T10:00:00Z")
    raw_v1 = reg.snapshot("equity-prices-raw", m.close_raw_v1, label="v1 vendor delivery", knowledge_time="2025-01-06",
                          notes="Initial delivery.")
    acts = reg.snapshot("corporate-actions", m.actions, label="v1", knowledge_time="2025-01-06")
    fund = reg.snapshot("fundamentals-quarterly", m.fundamentals, label="v1", knowledge_time="2025-01-06")
    uni = reg.snapshot("universe-pit", m.universe, label="v1", knowledge_time="2025-01-06")
    fut = reg.snapshot("futures-returns", m.futures_returns.rename("ret").to_frame(), label="v1",
                       knowledge_time="2025-01-06")
    tf_adj = reg.record_transform("adjust-prices", "adjustment", func=adjust_prices,
                                  params={"method": "backward factors P_e / ((P_e + D) * k)"},
                                  description="Total-return price adjustment for splits and dividends.")
    adj_v1 = reg.derive("equity-prices-adjusted", adjust_prices(m.close_raw_v1, m.actions), inputs=[raw_v1.id, acts.id],
                        transform=tf_adj, label="v1")
    tf_surv = reg.record_transform("survivors-only", "filter", code_ref="universe[status == 'listed']",
                                   params={"keep": "firms listed on 2024-12-31"},
                                   description="Drops every firm that was delisted or acquired.")
    surv = reg.derive("universe-survivors", m.survivors, inputs=[uni.id], transform=tf_surv, label="v1")
    holdout = reg.add_holdout("final-2020-2024", "2020-01-01", "2024-12-31", max_touches=3,
                              description="Sealed at the start of the project: three confirmatory looks allowed.")

    # ------------------------------------------------------------------ H-001 momentum (8 Jan)
    clock.set("2025-01-08T09:00:00Z")
    h1 = reg.add_hypothesis(
        "Cross-sectional momentum", "Firms with the highest 12-1 month returns outperform those with the lowest over "
        "the next month.", rationale="Well-documented anomaly; tested on the train window, judged on the test window.",
        prediction={"signal": "12-1 month return", "direction": "positive", "metric": "oos.sharpe"},
        criteria=[{"metric": "oos.sharpe", "op": ">=", "value": 0.3}, {"metric": "validation.dsr", "op": ">=", "value": 0.95}],
        family="momentum", register=True)
    base_data = {"prices": adj_v1.id, "universe": uni.id}
    clock.advance(minutes=20)
    mom_base = run("momentum", "Momentum 12-1, deciles", label="planted momentum (decays 2013-2016) plus quality spill-over",
                   real=True, params={"lookback_months": 12, "skip_months": 1, "quantile": 0.1, "cost_bps": 10},
                   seed=1, data=base_data, periods=periods, hypothesis=h1.id, model="xs-momentum", model_version="1",
                   holdout=holdout.id, tags=["momentum", "baseline"],
                   notes="Baseline exactly as pre-registered.")
    lookbacks = [6, 24] if quick else [3, 6, 9, 18, 24]
    for lb in lookbacks:
        run("momentum", f"Momentum {lb}-1, deciles", label="planted momentum", real=True,
            params={"lookback_months": lb, "skip_months": 1, "quantile": 0.1, "cost_bps": 10}, seed=1, data=base_data,
            periods=periods, hypothesis=h1.id, model="xs-momentum", model_version="1", holdout=holdout.id,
            tags=["momentum", "sweep"], notes="Formation-period sweep; every trial counts toward the deflated Sharpe.")

    # ------------------------------------------------------------------ H-002 quality (13-15 Jan)
    clock.set("2025-01-13T14:00:00Z")
    h2 = reg.add_hypothesis(
        "Profitability premium", "Firms with higher reported profitability outperform over the next month, using "
        "only reports already published.",
        rationale="Profitability is persistent; the market prices it slowly.",
        prediction={"signal": "published profitability", "direction": "positive", "metric": "oos.sharpe"},
        criteria=[{"metric": "oos.sharpe", "op": ">=", "value": 0.3}, {"metric": "validation.dsr", "op": ">=", "value": 0.95},
                  {"metric": "holdout.sharpe", "op": ">", "value": 0.0}],
        family="quality")
    clock.set("2025-01-14T16:30:00Z")
    q_data = {"prices": adj_v1.id, "universe": uni.id, "fundamentals": fund.id}
    run("quality", "Profitability, joined on period end", label="look-ahead: uses reports before publication",
        real=False, params={"quantile": 0.2, "point_in_time": False, "cost_bps": 10}, seed=1, data=q_data,
        periods=periods, hypothesis=h2.id, model="profitability", model_version="0", holdout=holdout.id,
        tags=["quality", "mistake"], notes="Quick first look before writing up the hypothesis.")
    clock.set("2025-01-15T09:00:00Z")
    reg.register_hypothesis(h2.id)
    reg.add_note("Registered after the first quick look; the look joined fundamentals on the period end.", hypothesis=h2.id)
    clock.advance(minutes=30)
    q_main = run("quality", "Profitability, point in time, quintiles", label="planted profitability effect", real=True,
                 params={"quantile": 0.2, "point_in_time": True, "cost_bps": 10}, seed=1, data=q_data, periods=periods,
                 hypothesis=h2.id, model="profitability", model_version="1", holdout=holdout.id, tags=["quality"],
                 notes="Main specification: reports enter on their publication date.")
    for qq in ([0.1] if quick else [0.1, 0.3]):
        run("quality", f"Profitability, point in time, top/bottom {qq:.0%}", label="planted profitability effect",
            real=True, params={"quantile": qq, "point_in_time": True, "cost_bps": 10}, seed=1, data=q_data,
            periods=periods, hypothesis=h2.id, model="profitability", model_version="1", holdout=holdout.id,
            tags=["quality", "robustness"], notes="Breakpoint robustness check.")

    # ------------------------------------------------------------------ H-003 futures trend (22 Jan)
    clock.set("2025-01-22T09:00:00Z")
    h3 = reg.add_hypothesis(
        "Trend following on futures", "A moving-average crossover rule on the futures contract earns a positive "
        "return.", rationale="Time-series momentum.",
        prediction={"signal": "MA crossover", "direction": "positive", "metric": "oos.sharpe"},
        criteria=[{"metric": "oos.sharpe", "op": ">=", "value": 0.3}], family="futures-trend", register=True)
    grid = ma_grid()
    if quick:
        grid = grid[::7]
    fut_data = {"index": fut.id}
    ma_ids = []
    for p in grid:
        ma_ids.append(run("ma_timing", f"MA {p['fast']}/{p['slow']} crossover", label="no planted edge (driftless contract)",
                          real=False, params={"fast": p["fast"], "slow": p["slow"], "cost_bps": 5}, seed=1,
                          data=fut_data, periods=periods, hypothesis=h3.id, model="ma-crossover", model_version="1",
                          holdout=holdout.id, tags=["futures", "sweep"]))
        clock.advance(minutes=2)
    run("ma_walk_forward", "MA crossover, walk-forward selection", label="no planted edge (driftless contract)",
        real=False, params={"train_years": 3, "cost_bps": 5}, seed=1, data=fut_data,
        periods=Periods.of(None, ("2008-01-01", "2019-12-31")),
        hypothesis=h3.id, model="ma-crossover", model_version="wf", holdout=holdout.id, tags=["futures", "walk-forward"],
        notes="Each year, trade the pair with the best record on all prior years: an honest estimate of the search.")

    # ------------------------------------------------------------------ H-004 continuation, then rewritten (3-5 Feb)
    clock.set("2025-02-03T09:00:00Z")
    h4 = reg.add_hypothesis(
        "Short-term continuation", "Last week's winners keep outperforming last week's losers next week.",
        prediction={"signal": "past-week return", "direction": "positive", "metric": "oos.sharpe"},
        criteria=[{"metric": "oos.sharpe", "op": ">=", "value": 0.3}], family="short-term", register=True)
    st_data = {"prices": adj_v1.id, "universe": uni.id}
    run("reversal", "Weekly continuation", label="planted short-term reversal (so continuation loses)", real=False,
        params={"direction": "continuation", "lookback_days": 5, "quantile": 0.1, "cost_bps": 10}, seed=1,
        data=st_data, periods=periods, hypothesis=h4.id, model="short-term", model_version="1", holdout=holdout.id,
        tags=["short-term"])
    clock.set("2025-02-05T11:00:00Z")
    reg.amend_hypothesis(h4.id, reason="The results show reversal, not continuation; restating the hypothesis.",
                         statement="Last week's losers outperform last week's winners next week.",
                         prediction={"signal": "past-week return", "direction": "negative", "metric": "oos.sharpe"})
    clock.advance(minutes=15)
    run("reversal", "Weekly reversal (same windows)", label="planted reversal, but confirmed on data already seen",
        real=True, params={"direction": "reversal", "lookback_days": 5, "quantile": 0.1, "cost_bps": 10}, seed=1,
        data=st_data, periods=periods, hypothesis=h4.id, model="short-term", model_version="2", holdout=holdout.id,
        tags=["short-term", "harking"])

    # ------------------------------------------------------------------ H-005 reversal, fresh test (10 Feb)
    clock.set("2025-02-10T09:00:00Z")
    h5 = reg.add_hypothesis(
        "Short-term reversal, fresh test", "Last week's losers outperform last week's winners next week after 10 bps "
        "trading costs.", rationale="Formed after H-004's results on 2005-2019, so only the sealed 2020-2024 holdout "
        "can confirm it.",
        prediction={"signal": "past-week return", "direction": "negative", "metric": "holdout.sharpe"},
        criteria=[{"metric": "holdout.sharpe", "op": ">", "value": 0.0}], family="reversal", register=True)
    reg.add_note("Follows H-004: the 2005-2019 data are spent for this idea.", hypothesis=h5.id)

    # ------------------------------------------------------------------ vendor correction (14 Feb)
    clock.set("2025-02-14T08:00:00Z")
    raw_v2 = reg.snapshot("equity-prices-raw", m.close_raw_v2, label="v2 vendor correction", knowledge_time="2025-02-14",
                          notes=f"The vendor corrected {len(m.bad_ticks)} bad prints present in v1.")
    adj_v2_frame = adjust_prices(m.close_raw_v2, m.actions)
    adj_v2 = reg.derive("equity-prices-adjusted", adj_v2_frame, inputs=[raw_v2.id, acts.id], transform=tf_adj,
                        label="v2")
    tf_mom = reg.record_transform("momentum-12-1", "feature", code_ref="prices.reindex(month_ends) shift(1)/shift(12) - 1",
                                  params={"lookback_months": 12, "skip_months": 1})
    me = month_ends(adj_v2_frame.index)
    pxm = adj_v2_frame.reindex(me)
    mom_feature = (pxm.shift(1) / pxm.shift(12) - 1.0).iloc[12:].round(8)
    reg.derive("feature-momentum-12-1", mom_feature, inputs=[adj_v2.id], transform=tf_mom, label="v2")
    tf_q = reg.record_transform("profitability-as-published", "feature",
                                code_ref="PointInTime(fundamentals).panel(month_ends, key=available_at)",
                                params={"join": "available_at", "frequency": "month end"})
    pit_view = PointInTime(m.fundamentals, entity="ticker", time="period_end", available="available_at")
    q_feature = pit_view.panel(me, "profitability", entities=list(adj_v2_frame.columns)).round(6)
    reg.derive("feature-profitability-pit", q_feature, inputs=[fund.id], transform=tf_q, label="v1")
    clock.advance(minutes=30)
    v2_data = {"prices": adj_v2.id, "universe": uni.id}
    run("momentum", "Momentum 12-1, deciles (data v2)", label="planted momentum", real=True,
        params={"lookback_months": 12, "skip_months": 1, "quantile": 0.1, "cost_bps": 10}, seed=1, data=v2_data,
        periods=periods, hypothesis=h1.id, model="xs-momentum", model_version="1", parent=mom_base, holdout=holdout.id,
        tags=["momentum", "data-v2"], notes="Re-run of the baseline on the corrected prices.")
    run("momentum", "Momentum 12-1, volatility-scaled", label="planted momentum", real=True,
        params={"lookback_months": 12, "skip_months": 1, "quantile": 0.1, "cost_bps": 10, "vol_scaled": True}, seed=1,
        data=v2_data, periods=periods, hypothesis=h1.id, model="xs-momentum", model_version="2", parent=mom_base,
        holdout=holdout.id, tags=["momentum", "model-v2"], notes="Model version 2: weights scaled by inverse 63-day volatility.")
    unseeded = run("momentum", "Momentum 12-1, randomised tie-break", label="planted momentum; unseeded randomness",
                   real=True, params={"lookback_months": 12, "skip_months": 1, "quantile": 0.1, "cost_bps": 10,
                                      "unseeded_tiebreak": True}, seed=1, data=v2_data, periods=periods,
                   hypothesis=h1.id, model="xs-momentum", model_version="2b", parent=mom_base, holdout=holdout.id,
                   tags=["momentum", "bug"], notes="Adds a random tie-break (from an unseeded generator).")
    q_v2 = {"prices": adj_v2.id, "universe": uni.id, "fundamentals": fund.id}

    # ------------------------------------------------------------------ H-006 past losers (20 Feb)
    clock.set("2025-02-20T09:00:00Z")
    h6 = reg.add_hypothesis(
        "Long-term reversal", "Firms with the worst 12-month returns outperform those with the best over the next month.",
        prediction={"signal": "past 12-month return", "direction": "negative", "metric": "oos.sharpe"},
        criteria=[{"metric": "oos.sharpe", "op": ">=", "value": 0.3}], family="long-term-reversal", register=True)
    run("past_losers", "Past losers, survivors-only universe", label="no planted effect; survivorship-biased data",
        real=False, params={"lookback_days": 252, "quantile": 0.1, "cost_bps": 10}, seed=1,
        data={"prices": adj_v2.id, "universe": surv.id}, periods=periods, hypothesis=h6.id, model="ltr",
        model_version="1", holdout=holdout.id, tags=["long-term-reversal", "mistake"],
        notes="Universe file taken from the current constituents list.")
    run("past_losers", "Past losers, full listing history", label="no planted effect", real=False,
        params={"lookback_days": 252, "quantile": 0.1, "cost_bps": 10}, seed=1, data={"prices": adj_v2.id, "universe": uni.id},
        periods=periods, hypothesis=h6.id, model="ltr", model_version="1", holdout=holdout.id, tags=["long-term-reversal"],
        notes="Same rule on every firm ever listed, delisting returns included.")

    # ------------------------------------------------------------------ data-handling check (24 Feb)
    clock.set("2025-02-24T10:00:00Z")
    run("reversal", "Weekly reversal on unadjusted prices", label="unadjusted prices: splits look like crashes",
        real=None, params={"direction": "reversal", "lookback_days": 5, "quantile": 0.1, "cost_bps": 10,
                           "raw_prices": True}, seed=1,
        data={"prices_raw": raw_v2.id, "universe": uni.id, "actions": acts.id}, periods=seen, hypothesis=h5.id,
        model="short-term", model_version="raw", holdout=holdout.id, tags=["reversal", "mistake"],
        notes="Exploratory run on the raw price file.")

    # ------------------------------------------------------------------ final holdout tests (3 Mar)
    clock.set("2025-03-03T09:00:00Z")
    q_final = run("quality", "Profitability, point in time - final holdout test", label="planted profitability effect",
                  real=True, params={"quantile": 0.2, "point_in_time": True, "cost_bps": 10}, seed=1, data=q_v2,
                  periods=periods, hypothesis=h2.id, model="profitability", model_version="1", holdout=holdout.id,
                  open_holdout=True, holdout_purpose="H-002 confirmatory test of the registered specification",
                  tags=["quality", "final"], notes="The registered main specification, unchanged, on the sealed holdout.")
    clock.advance(hours=2)
    run("reversal", "Weekly reversal - holdout test", label="planted reversal; costs decide", real=True,
        params={"direction": "reversal", "lookback_days": 5, "quantile": 0.1, "cost_bps": 10}, seed=1,
        data={"prices": adj_v2.id, "universe": uni.id}, periods=seen, hypothesis=h5.id, model="short-term",
        model_version="2", holdout=holdout.id, open_holdout=True, holdout_purpose="H-005 confirmatory test",
        tags=["reversal", "final"], notes="2005-2019 treated as in-sample: only the holdout can confirm H-005.")

    # ------------------------------------------------------------------ holdout over-use (10 Mar)
    clock.set("2025-03-10T15:00:00Z")
    ranked = sorted(ma_ids, key=lambda e: -(reg.get_experiment(e).metric("sharpe", "is") or -9))
    for eid in ranked[: (2 if quick else 6)]:
        p = reg.get_experiment(eid).params
        run("ma_timing", f"MA {p['fast']}/{p['slow']} crossover - holdout check", label="no planted edge; holdout re-used",
            real=False, params=p, seed=1, data=fut_data, periods=periods, hypothesis=h3.id, model="ma-crossover",
            model_version="1", holdout=holdout.id, open_holdout=True,
            holdout_purpose="checking the best in-sample pairs", tags=["futures", "holdout-reuse"])

    # ------------------------------------------------------------------ toy experiments (11 Mar)
    clock.set("2025-03-11T09:00:00Z")
    h7 = reg.add_hypothesis(
        "Toy: short-horizon trend in an AR(1) series", "In a synthetic series with first-order autocorrelation 0.08, "
        "holding the sign of the recent sum of returns earns a positive return.",
        prediction={"signal": "sign of trailing sum", "direction": "positive", "metric": "oos.sharpe"},
        criteria=[{"metric": "oos.sharpe", "op": ">", "value": 0.0}], family="toy", register=True)
    toy_ids = []
    for lb in (10, 20, 60):
        toy_ids.append(run("qros.examples.toy:toy_tsmom", f"Toy trend, {lb}-day window", label="planted AR(1) dependence",
                           real=True, params={"lookback": lb, "cost_bps": 5.0, "n": 1260}, seed=7, data={},
                           periods=Periods.of(("2015-01-01", "2017-12-31"), ("2018-01-01", "2019-12-31")),
                           hypothesis=h7.id, model="toy", model_version="1", tags=["toy", "browser-reproducible"],
                           notes="Small enough to re-run in a web browser bit for bit."))

    # ------------------------------------------------------------------ reproductions (12 Mar)
    clock.set("2025-03-12T09:00:00Z")
    for eid in (q_final, mom_base, toy_ids[1], unseeded):
        rec = reproduce(reg, eid)
        log(f"  reproduce {eid}: {rec['status']}")
        clock.advance(minutes=10)

    # ------------------------------------------------------------------ wrap-up (14 Mar)
    clock.set("2025-03-14T09:00:00Z")
    log("re-scoring every experiment against the final trial families")
    revalidate_all(reg)
    _set_statuses(reg)
    with db.transaction(reg.conn):
        db.set_meta(reg.conn, "demo", canonical_json({
            "seed": seed, "quick": quick, "synthetic": True, "market_truth": m.truth, "experiments": truth,
            "bad_ticks_v1": m.bad_ticks, "config": cfg.to_dict(),
            "note": "Synthetic data and simulated timestamps. Ground truth is known by construction."}))
    log(f"demo built in {time.time() - started:.0f}s: {reg.stats()['experiments']} experiments")
    return reg


def render_report(reg: Registry) -> str:
    """Markdown tables of the demo's results, generated from the registry (used for docs/DEMO.md)."""
    import json
    demo = json.loads(db.get_meta(reg.conn, "demo") or "{}")
    truth = demo.get("experiments", {})
    fmt = lambda v: "-" if v is None else f"{v:.2f}"  # noqa: E731
    lines = ["| ID | Experiment | Family | IS Sharpe | OOS Sharpe | Holdout Sharpe | DSR | Verdict | Planted truth |",
             "|---|---|---|---:|---:|---:|---:|---|---|"]
    for e in reg.list_experiments():
        rep = reg.latest_validation(e.id) or {}
        dsr = (rep.get("significance") or {}).get("dsr")
        t = truth.get(e.id, {})
        lines.append(f"| {e.id} | {e.name} | {e.family} | {fmt(e.metric('sharpe', 'is'))} | {fmt(e.metric('sharpe', 'oos'))} | "
                     f"{fmt(e.metric('sharpe', 'holdout'))} | {fmt(dsr)} | {e.verdict} | {t.get('label', '-')} |")
    hyp = ["| ID | Hypothesis | Status | Note |", "|---|---|---|---|"]
    for h in reg.list_hypotheses():
        hyp.append(f"| {h.id} | {h.title} | {h.status} | {(h.status_note or '').replace('Set by the demo script from the evidence: ', '')} |")
    counts: dict[str, int] = {}
    for w in reg.warnings():
        counts[w["code"]] = counts.get(w["code"], 0) + 1
    warn = ["| Warning | Active |", "|---|---:|"] + [f"| `{k}` | {v} |" for k, v in sorted(counts.items(), key=lambda kv: -kv[1])]
    reps = ["| Experiment | Re-run result |", "|---|---|"] + [f"| {r['experiment_id']} | {r['status']} |" for r in reg.reproductions()]
    verdicts: dict[str, int] = {}
    for e in reg.list_experiments():
        verdicts[e.verdict or e.status] = verdicts.get(e.verdict or e.status, 0) + 1
    chain = reg.verify(deep=False)["audit_chain"]
    head = (f"{reg.stats()['experiments']} experiments, {len(reg.list_hypotheses())} hypotheses, "
            f"{len(reg.list_versions())} dataset versions. Verdicts: "
            + ", ".join(f"{v} {k}" for k, v in sorted(verdicts.items(), key=lambda kv: -kv[1]))
            + f". Audit chain: {chain['events']} events, head `{chain['head'][:16]}`.")
    return "\n".join(["## Results (generated from the registry)", "", head, "", "### Experiments", "", *lines, "",
                      "### Hypotheses", "", *hyp, "", "### Active warnings", "", *warn, "", "### Reproductions", "", *reps, ""])


def _criteria_met(reg: Registry, exp_id: str, criteria: list[dict[str, Any]]) -> bool:
    exp = reg.get_experiment(exp_id)
    report = reg.latest_validation(exp_id) or {}
    ok = True
    for c in criteria or []:
        scope, _, name = c["metric"].partition(".")
        if scope == "validation":
            value = (report.get("significance") or {}).get(name)
        else:
            value = exp.metric(name, scope)
        if value is None:
            return False
        ok &= {">=": value >= c["value"], ">": value > c["value"], "<=": value <= c["value"],
               "<": value < c["value"]}[c["op"]]
    return bool(ok)


def _set_statuses(reg: Registry) -> None:
    for hyp in reg.list_hypotheses():
        exps = reg.list_experiments(hypothesis=hyp.id, status="completed")
        verdicts = {e.id: e.verdict for e in exps}
        crit = hyp.current.criteria or []
        robust = [e for e, v in verdicts.items() if v == "robust" and _criteria_met(reg, e, crit)]
        if any(w["code"] in ("HYPOTHESIS_AMENDED_AFTER_RESULTS",) for w in reg.warnings(hypothesis=hyp.id)):
            status, note = "abandoned", "Rewritten after its results; superseded by a freshly registered hypothesis."
        elif robust:
            status, note = "supported", f"Pre-registered criteria met by {', '.join(robust)} (verdict robust)."
        elif exps and all(v in ("invalid",) for v in verdicts.values()):
            status, note = "inconclusive", "Every test has an integrity problem."
        else:
            status, note = "rejected", "No test met the pre-registered criteria with a robust verdict."
        reg.set_hypothesis_status(hyp.id, status, note=f"Set by the demo script from the evidence: {note}",
                                  evidence=list(verdicts))
